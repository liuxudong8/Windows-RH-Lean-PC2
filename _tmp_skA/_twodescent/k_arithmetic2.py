import sympy as sp
import mpmath as mp

mp.mp.dps = 50
x = sp.symbols('x')
f = x**3 - 16*x + 16
u = sp.symbols('u')
g = u**3 + 6*u**2 - 52*u + 8

# --- 1. Eisenstein check & dK ---
print("=== 1. O_K, discriminant ===")
print("disc(g) =", sp.discriminant(g, u), "(expect 148)")
print("dK = 148, c = sqrt(disc(f)/dK) =", sp.sqrt(sp.Integer(9472)/148))
print("g Eisenstein at 2:", all(sp.Integer(c).p ** -1 < 1 for c in [6, -52, 8]) if False else
      (sp.Integer(6) % 2 == 0 and sp.Integer(-52) % 2 == 0 and sp.Integer(8) % 2 != 0 and sp.Integer(8) % 4 != 0))

# --- 2. prime ideal decomposition ---
print("\n=== 2. splitting ===")
print("f mod 2 = x^3  -> 2 totally ramified, 2 O_K = p2^3 (e=3,f=1)")
fac37 = sp.factor_list(f, modulus=37)
print("f mod 37:", [(str(a), e) for a, e in fac37[1]], "-> 37 = p37_1 * p37_2^2")
print("Minkowski bound M = (6/27)*sqrt(148) =", mp.mpf(6)/27*mp.sqrt(148))

# roots
th = [mp.mpf(str(r)) for r in sp.nroots(f, n=50)]
u_r = [2*t - 2 for t in th]
print("theta roots:", [mp.nstr(t, 10) for t in th])
print("u roots   :", [mp.nstr(t, 10) for t in u_r])
print("check g(u_i) = 0:", all(abs(sp.N(sp.simplify(g.subs(u, sp.Float(mp.nstr(r, 30)))), 15)) < mp.mpf('1e-25') for r in u_r))

