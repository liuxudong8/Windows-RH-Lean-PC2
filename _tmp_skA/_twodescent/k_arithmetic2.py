# direct norm formula with sympy
a, b, c = sp.symbols('a b c')
w = a + b*u + c*u**2
# norm = resultant? Use product over conjugates with symbolic roots is messy;
# instead compute norm via matrix of multiplication by w.
# basis 1, u, u^2:
# w*1 = a + b u + c u^2
# w*u = a u + b u^2 + c u^3 = -8c + (a+52c) u + (b-6c) u^2
# w*u^2 = a u^2 + b u^3 + c u^4 ; u^3 = -6u^2+52u-8 ; u^4 = u*u^3 = u(-6u^2+52u-8)
#   = -6u^3 + 52u^2 - 8u = -6(-6u^2+52u-8) + 52u^2 - 8u = 36u^2 - 312u + 48 + 52u^2 - 8u
#   = 88u^2 - 320u + 48
# w*u^2 = a u^2 + b(-6u^2+52u-8) + c(88u^2-320u+48)
#   = (-8b + 48c) + (52b - 320c) u + (a - 6b + 88c) u^2
M = sp.Matrix([
    [a, b, c],
    [-8*c, a + 52*c, b - 6*c],
    [-8*b + 48*c, 52*b - 320*c, a - 6*b + 88*c],
])
Nm = sp.expand(M.det())
print("\n=== 3. class group: p2 principal? ===")
print("norm(a+bu+cu^2) =", sp.factor(Nm))
# search small integer solutions of Nm = +-2
sols = []
for A in range(-12, 13):
    for B in range(-12, 13):
        for C in range(-12, 13):
            v = int(sp.N(Nm.subs({a: A, b: B, c: C})))
            if abs(v) == 2:
                sols.append((A, B, C, v))
print("N = +-2 integer solutions (|coeff|<=12):", sols)
if not sols:
    print("=> no small generator; h(K) likely 3 (p2 nonprincipal), else larger search")
    for A in range(-30, 31):
        for B in range(-30, 31):
            for C in range(-30, 31):
                v = int(sp.N(Nm.subs({a: A, b: B, c: C})))
                if abs(v) == 2:
                    sols.append((A, B, C, v))
    print("extended search (|coeff|<=30):", sols)

